#ifndef HANDLER_H
#define HANDLER_H

/*
 * 연결 하나의 요청을 읽고 알맞은 응답을 보낸다 (단계 4~8).
 * conn_fd: accept가 돌려준 연결 소켓. 이 함수는 conn_fd를 닫지 않는다 (닫는 것은 호출한 쪽의 몫).
 * root:    정적 파일 폴더 경로 (예: "./www")
 * 처리 순서와 응답:
 *   헤더를 끝까지 읽음      → 헤더가 버퍼보다 길면 431, 그 전에 연결이 닫히면 응답 없음
 *   요청 줄을 세 칸으로 나눔 → 형식이 틀리면 400
 *   HTTP 버전 확인          → HTTP/1.0, HTTP/1.1이 아니면 505
 *   메서드 확인             → GET, POST가 아니면 501
 *   헤더 확인               → HTTP/1.1인데 Host 헤더가 없으면 400
 *   요청 대상 확인          → '/'로 시작하지 않으면 400, ".." 칸이 있으면 403, 너무 길면 414
 *   POST면 본문을 읽음      → Content-Length가 없으면 411, 숫자가 아니면 400, 1MiB를 넘으면 413
 *   경로가 /cgi-bin/ 으로 시작 → CGI 프로그램을 실행해 그 출력을 보냄 (200, 404, 403, 500. src/cgi.c)
 *   그 밖의 경로에 POST     → 405 (정적 파일에는 허용하지 않음)
 *   그 밖의 경로에 GET      → 파일을 열어 보냄: 200, 없으면 404, 권한이 없거나 폴더면 403, 그 밖의 실패는 500
 */
void handle_connection(int conn_fd, const char *root);

#endif /* HANDLER_H */
